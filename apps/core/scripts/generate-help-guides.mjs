#!/usr/bin/env node
/**
 * Regenerate app/lib/assistant/help-docs/generated/guides.ts from the indexed guides (#1819).
 * A plain module loads under both Vite and tsx (the cron worker); `?raw` only under Vite.
 * help-docs.manifest.test.ts fails when the committed copy drifts from docs/.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const coreRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(coreRoot, "../..");
const outFile = path.join(coreRoot, "app/lib/assistant/help-docs/generated/guides.ts");

const SOURCES = {
  "user-guide": "docs/USER_GUIDE.md",
  "instructor-onboarding": "docs/INSTRUCTOR_ONBOARDING.md",
};

const entries = Object.entries(SOURCES).map(([id, file]) => {
  const text = fs.readFileSync(path.join(repoRoot, file), "utf8").replace(/\r\n/g, "\n");
  return `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`;
});

const output = `// Generated by apps/core/scripts/generate-help-guides.mjs from docs/ — do not edit.
// Run \`npm run help-docs:generate -w edu-ai\` after changing a guide.
export const HELP_GUIDE_SOURCES = {
${entries.join("\n")}
} as const;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output);
console.log(`[help-docs] wrote ${path.relative(repoRoot, outFile)}`);
